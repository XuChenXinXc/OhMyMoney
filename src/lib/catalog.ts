export function getToolBrand(tool: CatalogTool): ModelBrandMeta {
  const mapped = TOOL_TO_BRAND[tool.id];
  if (mapped && BRAND_CATALOG[mapped]) return BRAND_CATALOG[mapped];
  const id = tool.id.toLowerCase();
  for (const key of Object.keys(BRAND_CATALOG)) {
    if (id.startsWith(key)) return BRAND_CATALOG[key];
  }
  return {
    id: tool.id,
    nameZh: tool.name,
    nameEn: tool.nameEn,
    badge: tool.category.toUpperCase(),
    region: tool.region,
    category: tool.category,
    tagsZh: [tool.category === "coding" ? "编程" : tool.category === "visual" ? "图像视频" : tool.category === "search" ? "搜索" : tool.category === "audio" ? "音频" : "对话"],
    tagsEn: [tool.category],
  };
}

